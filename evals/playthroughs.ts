import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { parseTags, serializeAttrs } from "../lib/parsetags";
import { esc, STYLE } from "./page";

/**
 * Render the recorded quest runs (evals/quests/*.yaml) as static HTML pages.
 *
 * The pages are a technical demonstration, not a game surface: they show the
 * machinery — the player model's own notes, the milestones as they are hit,
 * the repeats and snags — with enough exposition that a reader who has never
 * seen the project can follow what the apparatus is doing and why.
 *
 * Same contract as the eval page: self-contained HTML, generated by
 * `pnpm playthroughs`, committed, and copied into dist/ by the build, so the
 * deploy needs no model and no data files.
 *
 *   pnpm playthroughs
 */

const root = dirname(fileURLToPath(import.meta.url));
const QUESTS = resolve(root, "quests");
const OUT = resolve(root, "playthroughs");

interface QuestEvent {
  id: string;
  title?: string;
  response?: string;
  changes?: string[];
  roll?: number;
}

interface QuestTurn {
  n: number;
  input: string;
  notes?: string;
  saw?: string[];
  reached?: string[];
  machinery?: QuestEvent[];
}

interface QuestRun {
  quest: string;
  playerModel: string;
  gameModel: string;
  solved: boolean;
  turns: number;
  maxTurns: number;
  milestones: string[];
  missed: string[];
  roomsVisited: string[];
  repeats: number;
  fumbles?: number;
  snags?: { turn: number; text: string }[];
  dropped?: string[];
  ms: number;
  error?: string;
  log: QuestTurn[];
}

interface NamedRun {
  slug: string;
  date: string;
  run: QuestRun;
}

function loadRuns(): NamedRun[] {
  return readdirSync(QUESTS)
    .filter((file) => file.endsWith(".yaml"))
    .sort()
    .map((file) => {
      const slug = file.replace(/\.yaml$/, "");
      // ink-and-echo-2026-07-31-11-09-18 -> "2026-07-31 11:09"
      const m = /-(\d{4}-\d{2}-\d{2})-(\d{2})-(\d{2})-\d{2}$/.exec(slug);
      const date = m ? `${m[1]} ${m[2]}:${m[3]}` : slug;
      const run = parse(readFileSync(resolve(QUESTS, file), "utf8"));
      return { slug, date, run };
    });
}

const SPOILERS = `<p class="spoiler">Warning: these transcripts can show the
solutions to the mysteries of the game. If you want to find the solutions in
play, <a href="/">play the game first</a>.</p>`;

/**
 * The apparatus, explained once on the index and linked from each run. The
 * exposition is written to ASD-STE100 (Simplified Technical English): short
 * sentences, one idea in each sentence, the same word for the same thing.
 */
const APPARATUS = `
<h2>How a quest run works</h2>
<p>Two models operate in each run. The <strong>game model</strong> plays all
the characters, describes the rooms, and sends the tags that the engine
obeys. This is the same configuration as normal play.</p>
<p>The <strong>player model</strong> plays the player. It can see only the
data that a human player can see: the transcript, the current room, the
exits, the persons in the room, the task list, and the names of the open
mysteries. It cannot see the mystery hints. It cannot see the character
instructions. The code in <code>evals/playerview.ts</code> makes this view. A
test makes sure that the mystery answers are not in the view.</p>
<p>The player model keeps notes between its turns. The notes are its memory.
It writes the notes for itself. The pages below show the notes without
changes. The notes show what the player model believed, and what it planned,
before each turn.</p>
<p>The engine measures progress. It does not ask a model for an opinion. A
milestone, for example <code>met-marta</code>, is a check of the world state
after each turn. A mystery counts as solved only when the game fires its own
<code>&lt;resolveMystery&gt;</code> instruction.</p>
<p>The pages show these counts also. <strong>Repeats</strong> is the number
of turns where the player went to the same room again, or asked the same
question again. <strong>Fumbles</strong> is the number of commands that the
game could not use. <strong>Snags</strong> are moments where the game gave
incorrect information to the player. A snag is a defect in the game, not in
the player.</p>`;

function pill(text: string, cls: string): string {
  return `<span class="pill ${cls}">${esc(text)}</span>`;
}

function summaryTable(run: QuestRun): string {
  const rows: [string, string][] = [
    ["player model", run.playerModel],
    ["game model", run.gameModel],
    ["solved", run.solved ? "yes" : "no"],
    ["turns used", `${run.turns} of ${run.maxTurns}`],
    [
      "milestones",
      `${run.milestones.length} of ${run.milestones.length + run.missed.length}` +
        (run.milestones.length ? ` — ${run.milestones.join(", ")}` : ""),
    ],
    ["missed", run.missed.length ? run.missed.join(", ") : "none"],
    ["rooms visited", run.roomsVisited.join(", ")],
    ["repeated itself", `${run.repeats} turns`],
    ["wall clock", `${Math.round(run.ms / 60000)} min`],
  ];
  if (run.fumbles !== undefined) {
    rows.push(["fumbled commands", String(run.fumbles)]);
  }
  const body = rows
    .map(
      ([k, v]) =>
        `<tr><th scope="row">${esc(k)}</th><td>${esc(v)}</td></tr>`,
    )
    .join("\n");
  return `<div class="scroller"><table class="summary">${body}</table></div>`;
}

/**
 * One engine event, rendered the way the game's own debug view renders it:
 * each tag on its own header line, its content under it. This is where the
 * <context> judgment steps, <mind>, and <attitude> become visible.
 */
function eventBlock(event: QuestEvent): string {
  const parts: string[] = [];
  if (event.response) {
    for (const tag of parseTags(event.response)) {
      if (tag.type === "comment") {
        parts.push(`<pre class="tagbody">${esc(tag.content)}</pre>`);
        continue;
      }
      parts.push(
        `<div class="tagname">&lt;${esc(tag.type)}${esc(serializeAttrs(tag.attrs))}&gt;</div>`,
      );
      if (tag.content.trim()) {
        parts.push(`<pre class="tagbody">${esc(tag.content.trim())}</pre>`);
      }
    }
  }
  if (event.roll !== undefined) {
    parts.push(`<div class="changes">d20: ${event.roll}</div>`);
  }
  if (event.changes?.length) {
    parts.push(
      `<div class="changes">${event.changes.map(esc).join("<br>")}</div>`,
    );
  }
  return `<div class="event">
  <div class="eventhead">${esc(event.id)}${event.title ? ` <span class="meta">${esc(event.title)}</span>` : ""}</div>
  ${parts.join("\n")}
</div>`;
}

function machineryBlock(turn: QuestTurn): string {
  if (!turn.machinery?.length) {
    return "";
  }
  return `<details class="machinery" open>
  <summary>engine record: ${turn.machinery.length} event${turn.machinery.length === 1 ? "" : "s"}</summary>
  <p class="note">This is the side of the turn that the player model cannot
  see: the game model's numbered thoughts (<code>&lt;context&gt;</code>), the
  private notes of the characters (<code>&lt;mind&gt;</code>), their feelings
  (<code>&lt;attitude&gt;</code>), the state changes, and the dice.</p>
  ${turn.machinery.map(eventBlock).join("\n")}
</details>`;
}

function turnBlock(turn: QuestTurn): string {
  const reached = (turn.reached ?? [])
    .map((m) => pill(m, "reached"))
    .join(" ");
  const notes = turn.notes
    ? `<div class="notes"><div class="label">notes of the player model, before this turn</div>
       <pre>${esc(turn.notes)}</pre></div>`
    : "";
  const saw = (turn.saw ?? [])
    .map((line) => `<pre class="saw">${esc(line)}</pre>`)
    .join("\n");
  return `
<section class="turn">
  <h2>Turn ${turn.n} ${reached}</h2>
  ${notes}
  <p class="cmd"><span class="label">command</span> <code>${esc(turn.input)}</code></p>
  <div class="label">game output</div>
  ${saw}
  ${machineryBlock(turn)}
</section>`;
}

function runPage(named: NamedRun): string {
  const { run, date } = named;
  const snags = (run.snags ?? []).length
    ? `<h2>Snags</h2>
       <p>The harness found moments where the game gave incorrect information
       to the player. These are defects in the game, not in the player. We
       keep them because they show what to repair.</p>
       ${(run.snags ?? []).map((s) => `<pre class="saw">turn ${s.turn}: ${esc(s.text)}</pre>`).join("\n")}`
    : "";
  const error = run.error
    ? `<h2>How the run ended</h2>
       <p class="note">The run stopped early: <code>${esc(run.error)}</code>.
       We record this, because a timeout is also a result.</p>`
    : "";
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Intra playthrough — ${esc(run.quest)} — ${esc(date)}</title>
<style>${STYLE}${EXTRA_STYLE}</style>
</head>
<body>
<header>
  <p class="note"><a href="./">all playthroughs</a> · <a href="/evals/">evals</a> · <a href="/">the game</a></p>
  <h1>${esc(run.quest)} — ${esc(date)}</h1>
  <p>A model plays Intra. It can see only the data a player can see. It keeps
  its own notes between turns. The engine measures its progress against the
  world state. <a href="./">Read how the system works.</a></p>
  ${SPOILERS}
</header>
${summaryTable(run)}
<p>Each turn below has three parts, in this sequence: the notes that the
player model had before the turn, the command that it typed, and the output
that the game gave. The notes show why the turn occurred. You cannot get
this data from the game output alone.</p>
${
  run.log.some((turn) => turn.machinery?.length)
    ? `<p>Some turns also have an <strong>engine record</strong>. It shows the
side of the turn that the player model cannot see: the game model's numbered
thoughts, the private notes and feelings of the characters, the state
changes, and the dice.</p>`
    : `<p class="note">This run is older than the engine recording. Its turns
do not have engine records.</p>`
}
${run.log.map(turnBlock).join("\n")}
${snags}
${error}
<footer>
  <p><a href="./">All playthroughs</a> · <a href="/evals/">the eval scoreboard</a> · <a href="/">play Intra</a></p>
</footer>
</body>
</html>
`;
}

function indexPage(runs: NamedRun[]): string {
  const rows = runs
    .map(({ slug, date, run }) => {
      const total = run.milestones.length + run.missed.length;
      return `<tr>
  <td><a href="${esc(slug)}.html">${esc(date)}</a></td>
  <td><code>${esc(run.quest)}</code></td>
  <td class="score ${run.solved ? "pass" : "fail"}">${run.solved ? "solved" : "unsolved"}</td>
  <td class="score">${run.milestones.length}/${total}</td>
  <td class="score">${run.turns}</td>
  <td class="score">${run.repeats}</td>
</tr>`;
    })
    .join("\n");
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Intra — recorded playthroughs</title>
<style>${STYLE}${EXTRA_STYLE}</style>
</head>
<body>
<header>
  <p class="note"><a href="/evals/">evals</a> · <a href="/">the game</a></p>
  <h1>Watching a model play</h1>
  <p><a href="/">Intra</a> is a text adventure. A language model operates the
  game. In the recordings below, a different model plays the game. The player
  model has a quest to complete and a limit on its turns. Nobody helps it.</p>
  <p>We made these recordings to answer a development question: can a model
  play this game, and where does play stop? We publish the failed runs
  together with the good runs, because the failed runs show more.</p>
  ${SPOILERS}
</header>
${APPARATUS}
<h2>The runs</h2>
<p>The table shows all the recorded runs. A failed run has value. One 20-turn
run did not go out of the archive area. That run showed us that a player can
stay too long with one lead. The snag logs from these runs caused several
engine repairs.</p>
<div class="scroller">
<table>
<thead><tr><th>run</th><th>quest</th><th>outcome</th><th>milestones</th><th>turns</th><th>repeats</th></tr></thead>
<tbody>
${rows}
</tbody>
</table>
</div>
<footer>
  <p>The command <code>pnpm playthroughs</code> makes these pages from the
  YAML files in <code>evals/quests/</code>. The harness is
  <code>evals/runquest.ts</code>. The player view is
  <code>evals/playerview.ts</code>. The <a href="/evals/">eval page</a> shows
  scores for short, separate scenarios.</p>
</footer>
</body>
</html>
`;
}

