function main() {
  const runs = loadRuns();
  mkdirSync(OUT, { recursive: true });
  for (const named of runs) {
    writeFileSync(resolve(OUT, `${named.slug}.html`), runPage(named));
  }
  writeFileSync(resolve(OUT, "index.html"), indexPage(runs));
  console.log(
    `wrote evals/playthroughs/: index + ${runs.length} run page${runs.length === 1 ? "" : "s"}`,
  );
}

main();
