import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";
import { renderPage, type ResultsFile } from "./page";
import { EVAL_SCENARIOS } from "./scenarios";

/**
 * Turn the recorded YAML into the two things people actually read.
 *
 * Separate from run.ts so the reports can be rebuilt without spending live
 * model calls — `pnpm evals:report` after editing the page template or adding a
 * scenario name.
 */

export const RESULTS_DIR = "evals/results";
export const SUMMARY = "evals/RESULTS.md";
export const PAGE = "evals/index.html";

export function readResults(): ResultsFile[] {
  return readdirSync(RESULTS_DIR)
    .filter((f) => f.endsWith(".yaml"))
    .sort()
    .reverse()
    .map(
      (f) => parse(readFileSync(join(RESULTS_DIR, f), "utf8")) as ResultsFile,
    );
}

/**
 * Which prompts a day's numbers were measured against.
 *
 * Not a warning when they differ — mixing is normal, since re-running one
 * scenario after a prompt edit is exactly the thing merging supports. It just
 * has to be visible, because two rows measured against different prompts are
 * not comparable and nothing else in the table says so.
 */
export function fingerprintNote(data: ResultsFile): string {
  const seen = [
    ...new Set(
      data.runs.flatMap((run) =>
        run.scenarios.map((s) => s.promptFingerprint).filter(Boolean),
      ),
    ),
  ] as string[];
  if (!seen.length) {
    return "Recorded before prompt fingerprints, so what was measured isn't known.";
  }
  if (seen.length === 1) {
    return `Prompts \`${seen[0]}\`.`;
  }
  return (
    `Prompts ${seen.map((f) => `\`${f}\``).join(", ")} — rows here were ` +
    `measured against different prompts and aren't directly comparable.`
  );
}

/** Rebuild the summary and the page from every recorded run, newest first. */
export function writeReports() {
  const files = readResults();
  const scenarioNames = EVAL_SCENARIOS.map((s) => s.name);

  const lines: string[] = [
    "# Eval results",
    "",
    "Generated by `pnpm evals` — do not edit by hand. The same data is rendered",
    "as a page in [index.html](./index.html), and recorded as YAML under",
    "[results/](./results/).",
    "",
    "Each cell is checks passed out of checks run for that scenario. What the",
    "checks are, and why, is in [scenarios.ts](./scenarios.ts).",
    "",
  ];

  for (const data of files) {
    lines.push(`## ${data.date}`, "");
    lines.push(fingerprintNote(data), "");
    lines.push(`| model | ${scenarioNames.join(" | ")} | total |`);
    lines.push(`| --- | ${scenarioNames.map(() => "---").join(" | ")} | --- |`);
    for (const run of data.runs) {
      const cells = scenarioNames.map((name) => {
        const result = run.scenarios.find((s) => s.scenario === name);
        if (!result) return "–";
        return `${result.passed}/${result.total}`;
      });
      const passed = run.scenarios.reduce((a, s) => a + s.passed, 0);
      const total = run.scenarios.reduce((a, s) => a + s.total, 0);
      lines.push(
        `| \`${run.model}\`${run.flashModel ? ` + \`${run.flashModel}\`` : ""} | ${cells.join(" | ")} | **${passed}/${total}** |`,
      );
    }
    lines.push("");

    const failures = data.runs.flatMap((run) =>
      run.scenarios.flatMap((s) =>
        s.checks
          .filter((c) => !c.passed)
          .map(
            (c) => `- \`${run.model}\` ${s.scenario}/${c.name}: ${c.describe}`,
          ),
      ),
    );
    if (failures.length) {
      lines.push("What failed:", "", ...failures, "");
    }
  }

  writeFileSync(SUMMARY, `${lines.join("\n")}\n`);
  writeFileSync(PAGE, renderPage(files, scenarioNames));
}
