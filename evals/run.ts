import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { ChatFn } from "../lib/game/model";
import { cliChat } from "../playtest/clichat";
import { runScenario, type ScenarioResult } from "./harness";
import { openRouterChat } from "./openrouter";
import { EVAL_SCENARIOS } from "./scenarios";

/**
 * Run the eval scenarios against one or more models and record the results.
 *
 *     pnpm evals                                  # the default models, cli backend
 *     pnpm evals --model claude-haiku-4-5-20251001
 *     pnpm evals --backend openrouter --model anthropic/claude-haiku-4.5
 *     pnpm evals --scenario intake
 *
 * Results land in evals/results/<date>.json and are rolled up into
 * evals/RESULTS.md. Both are committed: the point of an eval you can't rerun
 * cheaply is the record it leaves.
 */

const RESULTS_DIR = "evals/results";
const SUMMARY = "evals/RESULTS.md";

interface ModelRun {
  model: string;
  backend: string;
  scenarios: ScenarioResult[];
}

interface ResultsFile {
  date: string;
  runs: ModelRun[];
}

function parseArgs(argv: string[]) {
  const args: Record<string, string[]> = {};
  let key = "";
  for (const token of argv) {
    if (token.startsWith("--")) {
      key = token.slice(2);
      args[key] ??= [];
    } else if (key) {
      args[key]!.push(token);
    }
  }
  return args;
}

function backendFor(name: string, model: string): ChatFn {
  if (name === "openrouter") {
    return openRouterChat({ model });
  }
  if (name === "cli") {
    return cliChat({ model });
  }
  throw new Error(`Unknown backend "${name}" (expected cli or openrouter)`);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const backend = args.backend?.[0] ?? "cli";
  const models = args.model?.length
    ? args.model
    : backend === "cli"
      ? ["claude-haiku-4-5-20251001", "claude-sonnet-4-5-20250929"]
      : ["anthropic/claude-haiku-4.5"];
  const only = args.scenario ?? [];
  const scenarios = only.length
    ? EVAL_SCENARIOS.filter((s) => only.includes(s.name))
    : EVAL_SCENARIOS;
  if (!scenarios.length) {
    throw new Error(`No scenarios matched ${only.join(", ")}`);
  }

  const runs: ModelRun[] = [];
  for (const model of models) {
    console.log(`\n=== ${model} (${backend}) ===`);
    const results: ScenarioResult[] = [];
    for (const scenario of scenarios) {
      process.stdout.write(`  ${scenario.name}... `);
      const result = await runScenario(scenario, backendFor(backend, model));
      results.push(result);
      const failed = result.checks.filter((c) => !c.passed).map((c) => c.name);
      console.log(
        `${result.passed}/${result.total} in ${Math.round(result.ms / 1000)}s` +
          (failed.length ? ` — failed: ${failed.join(", ")}` : "") +
          (result.error ? ` — ERROR ${result.error}` : ""),
      );
      for (const warning of result.dropped.slice(0, 3)) {
        console.log(`      dropped: ${warning.slice(0, 110)}`);
      }
      for (const warning of result.repaired.slice(0, 2)) {
        console.log(`      repaired: ${warning.slice(0, 110)}`);
      }
    }
    runs.push({ model, backend, scenarios: results });
  }

  const date = new Date().toISOString().slice(0, 10);
  mkdirSync(RESULTS_DIR, { recursive: true });
  const path = join(RESULTS_DIR, `${date}.json`);
  writeFileSync(path, `${JSON.stringify({ date, runs }, null, 2)}\n`);
  console.log(`\nwrote ${path}`);
  writeSummary();
  console.log(`wrote ${SUMMARY}`);
}

/** Rebuild RESULTS.md from every recorded run, newest first. */
function writeSummary() {
  const files = readdirSync(RESULTS_DIR)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .reverse();
  const scenarioNames = EVAL_SCENARIOS.map((s) => s.name);

  const lines: string[] = [
    "# Eval results",
    "",
    "Generated by `pnpm evals` — do not edit by hand.",
    "",
    "Each cell is checks passed out of checks run for that scenario. What the",
    "checks are, and why, is in [scenarios.ts](./scenarios.ts).",
    "",
  ];

  for (const file of files) {
    const data = JSON.parse(
      readFileSync(join(RESULTS_DIR, file), "utf8"),
    ) as ResultsFile;
    lines.push(`## ${data.date}`, "");
    lines.push(`| model | ${scenarioNames.join(" | ")} | total |`);
    lines.push(`| --- | ${scenarioNames.map(() => "---").join(" | ")} | --- |`);
    for (const run of data.runs) {
      const cells = scenarioNames.map((name) => {
        const result = run.scenarios.find((s) => s.scenario === name);
        if (!result) return "–";
        return `${result.passed}/${result.total}`;
      });
      const passed = run.scenarios.reduce((a, s) => a + s.passed, 0);
      const total = run.scenarios.reduce((a, s) => a + s.total, 0);
      lines.push(
        `| \`${run.model}\` | ${cells.join(" | ")} | **${passed}/${total}** |`,
      );
    }
    lines.push("");

    const failures = data.runs.flatMap((run) =>
      run.scenarios.flatMap((s) =>
        s.checks
          .filter((c) => !c.passed)
          .map(
            (c) => `- \`${run.model}\` ${s.scenario}/${c.name}: ${c.describe}`,
          ),
      ),
    );
    if (failures.length) {
      lines.push("What failed:", "", ...failures, "");
    }
  }

  writeFileSync(SUMMARY, `${lines.join("\n")}\n`);
}

await main();
